"""Builds 01_dataset_check.ipynb (the dataset-loading notebook for the report)."""
import nbformat as nbf

nb = nbf.v4.new_notebook()
md, code = nbf.v4.new_markdown_cell, nbf.v4.new_code_cell

nb.cells = [
    md("# EuroSAT (RGB) — dataset check\n"
       "CPS 4841 course project, dataset selection step.\n\n"
       "This notebook downloads EuroSAT RGB, counts images per class, plots the class "
       "distribution, shows sample images with their labels, and verifies the annotations "
       "(folder-name labels). It runs top to bottom in a fresh Google Colab runtime.\n\n"
       "Dataset: Helber et al., *EuroSAT: A Novel Dataset and Deep Learning Benchmark for Land Use "
       "and Land Cover Classification*, IEEE JSTARS 2019. Download: https://zenodo.org/records/7711810 (MIT license)."),
    code("# 1. Download and unzip (about 90 MB). Skipped if the data is already present.\n"
         "import os, urllib.request, zipfile\n"
         "URL = 'https://zenodo.org/records/7711810/files/EuroSAT_RGB.zip'\n"
         "DATA_DIR = 'data'\n"
         "ROOT = os.path.join(DATA_DIR, 'EuroSAT_RGB')\n"
         "os.makedirs(DATA_DIR, exist_ok=True)\n"
         "if not os.path.isdir(ROOT):\n"
         "    zip_path = os.path.join(DATA_DIR, 'EuroSAT_RGB.zip')\n"
         "    urllib.request.urlretrieve(URL, zip_path)\n"
         "    with zipfile.ZipFile(zip_path) as z:\n"
         "        z.extractall(DATA_DIR)\n"
         "print('Dataset folder:', ROOT)\n"
         "print('Class folders:', sorted(os.listdir(ROOT)))"),
    code("# 2. Count images per class and check every file opens as a 64x64 RGB image\n"
         "import glob, collections\n"
         "import numpy as np, pandas as pd\n"
         "from PIL import Image\n\n"
         "CLASSES = sorted(d for d in os.listdir(ROOT) if os.path.isdir(os.path.join(ROOT, d)))\n"
         "records, bad, shapes = [], [], collections.Counter()\n"
         "for label_id, cls in enumerate(CLASSES):\n"
         "    for path in sorted(glob.glob(os.path.join(ROOT, cls, '*.jpg'))):\n"
         "        try:\n"
         "            with Image.open(path) as im:\n"
         "                shapes[(im.size, im.mode)] += 1\n"
         "            records.append({'path': path, 'label': cls, 'label_id': label_id})\n"
         "        except Exception as e:\n"
         "            bad.append((path, str(e)))\n"
         "df = pd.DataFrame(records)\n"
         "print('Number of classes:', len(CLASSES))\n"
         "print('Total images     :', len(df))\n"
         "print('Unreadable files :', len(bad))\n"
         "print('Image size / mode:', dict(shapes))\n"
         "counts = df['label'].value_counts().reindex(CLASSES)\n"
         "table = pd.DataFrame({'images': counts, 'percent': (100 * counts / counts.sum()).round(2)})\n"
         "table"),
    code("# 3. Class distribution: bar chart and pie chart\n"
         "import matplotlib.pyplot as plt\n"
         "os.makedirs('figures', exist_ok=True)\n"
         "fig, axes = plt.subplots(1, 2, figsize=(13, 4.8))\n"
         "bars = axes[0].bar(CLASSES, counts.values, color='#3b6ea5')\n"
         "axes[0].bar_label(bars, fontsize=8)\n"
         "axes[0].set_ylabel('Number of images'); axes[0].set_title('Images per class')\n"
         "axes[0].tick_params(axis='x', rotation=45)\n"
         "for t in axes[0].get_xticklabels(): t.set_ha('right')\n"
         "axes[0].spines[['top', 'right']].set_visible(False)\n"
         "axes[1].pie(counts.values, labels=CLASSES, autopct='%1.1f%%', startangle=90,\n"
         "            textprops={'fontsize': 8}, colors=plt.cm.tab10.colors)\n"
         "axes[1].set_title('Share of the dataset')\n"
         "plt.tight_layout(); plt.savefig('figures/class_distribution.png', dpi=200); plt.show()"),
    code("# 4. Planned split: stratified 70 / 15 / 15 (train / val / test), fixed seed\n"
         "# EuroSAT has no official split, so we make one and keep the class ratios equal in every part.\n"
         "rng = np.random.default_rng(42)\n"
         "split = np.empty(len(df), dtype=object)\n"
         "for cls in CLASSES:\n"
         "    idx = rng.permutation(df.index[df['label'] == cls].to_numpy())\n"
         "    n_tr, n_va = int(0.70 * len(idx)), int(0.15 * len(idx))\n"
         "    split[idx[:n_tr]] = 'train'; split[idx[n_tr:n_tr + n_va]] = 'val'; split[idx[n_tr + n_va:]] = 'test'\n"
         "df['split'] = split\n"
         "split_table = pd.crosstab(df['label'], df['split'], margins=True, margins_name='Total')[['train', 'val', 'test', 'Total']]\n"
         "df[['path', 'label', 'label_id', 'split']].to_csv('splits.csv', index=False)\n"
         "split_table"),
    code("# 5. Proof that the data loads: 3 random images per class with their labels\n"
         "rng = np.random.default_rng(0)\n"
         "fig, axes = plt.subplots(3, len(CLASSES), figsize=(16, 5.4))\n"
         "for c, cls in enumerate(CLASSES):\n"
         "    paths = rng.choice(df.loc[df['label'] == cls, 'path'].to_numpy(), 3, replace=False)\n"
         "    for r, p in enumerate(paths):\n"
         "        ax = axes[r, c]\n"
         "        ax.imshow(Image.open(p)); ax.set_xticks([]); ax.set_yticks([])\n"
         "        ax.set_xlabel(os.path.basename(p), fontsize=6)\n"
         "        if r == 0: ax.set_title(f'{cls}\\n(label {c})', fontsize=8)\n"
         "plt.tight_layout(); plt.savefig('figures/sample_grid.png', dpi=200); plt.show()"),
    code("# 6. Annotation verification\n"
         "# Each image's label is the name of the folder it sits in, and the file name repeats it\n"
         "# (e.g. Forest/Forest_12.jpg). Check that the two always agree and that nothing is duplicated.\n"
         "import hashlib\n"
         "df['file_prefix'] = df['path'].map(lambda p: os.path.basename(p).rsplit('_', 1)[0])\n"
         "mismatch = (df['file_prefix'] != df['label']).sum()\n"
         "print('Images with a label        :', df['label'].notna().sum(), 'of', len(df))\n"
         "print('Folder/file-name mismatches:', mismatch)\n"
         "print('Duplicate file paths       :', df['path'].duplicated().sum())\n"
         "md5 = df['path'].map(lambda p: hashlib.md5(open(p, 'rb').read()).hexdigest())\n"
         "print('Byte-identical duplicates  :', md5.duplicated().sum())\n"
         "print('Label ids                  :', dict(enumerate(CLASSES)))"),
    code("# 7. Mean RGB colour per class (shows the classes differ in simple colour statistics,\n"
         "#    which is what the colour-histogram baseline will rely on)\n"
         "sub = df.groupby('label').sample(300, random_state=0)\n"
         "means = sub.groupby('label')['path'].apply(lambda ps: np.mean([np.asarray(Image.open(p), dtype=np.float32).mean((0, 1)) for p in ps], axis=0))\n"
         "rgb = pd.DataFrame(means.tolist(), index=means.index, columns=['R', 'G', 'B']).reindex(CLASSES).round(1)\n"
         "ax = rgb.plot.bar(figsize=(10, 3.8), color=['#c0392b', '#27ae60', '#2e6fb5'], width=0.8)\n"
         "ax.set_ylabel('Mean pixel value (0-255)'); ax.set_xlabel(''); ax.set_ylim(0, 165)\n"
         "ax.legend(ncol=3, loc='upper center', frameon=False); ax.set_title('Mean RGB per class (300 random images per class)')\n"
         "ax.tick_params(axis='x', rotation=45)\n"
         "for t in ax.get_xticklabels(): t.set_ha('right')\n"
         "ax.spines[['top', 'right']].set_visible(False)\n"
         "plt.tight_layout(); plt.savefig('figures/mean_rgb.png', dpi=200); plt.show()\n"
         "rgb"),
]
nb.metadata["kernelspec"] = {"name": "python3", "display_name": "Python 3", "language": "python"}
nbf.write(nb, "01_dataset_check.ipynb")
print("written")
